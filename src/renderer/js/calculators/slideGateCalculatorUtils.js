/**
 * Линейная интерполяция между двумя точками
 */
function lerp(value1, value2, ratio) {
	return value1 + (value2 - value1) * ratio;
}

/**
 * Интерполяция по ширине для конкретной высоты
 */
function interpolateWidth(tableRow, W_proem) {
	const widths = tableRow.map((row) => row[0]);

	// Ограничиваем ширину диапазоном таблицы
	W_proem = Math.max(widths[0], Math.min(widths[widths.length - 1], W_proem));

	// Находим интервал
	let idx = 0;
	for (let i = 0; i < tableRow.length - 1; i++) {
		if (W_proem >= tableRow[i][0] && W_proem <= tableRow[i + 1][0]) {
			idx = i;
			break;
		}
	}

	const p0 = tableRow[idx];
	const p1 = tableRow[idx + 1];
	const ratio = (W_proem - p0[0]) / (p1[0] - p0[0]);

	return {
		height: lerp(p0[1], p1[1], ratio),
		topWidth: lerp(p0[2], p1[2], ratio),
		bottomWidth: lerp(p0[3], p1[3], ratio),
	};
}

/**
 * Двумерная интерполяция (по ширине и высоте)
 */
function interpolateFromTable(W_proem, H_proem, isRectangular) {
	const tableType = isRectangular ? "rectangular" : "triangular";
	const table = GATE_TABLE_DATA[tableType];
	const heights = Object.keys(table)
		.map(Number)
		.sort((a, b) => a - b);

	// Ограничиваем высоту
	H_proem = Math.max(heights[0], Math.min(heights[heights.length - 1], H_proem));

	// Находим интервал по высоте
	let lowerHeight = heights[0];
	let upperHeight = heights[heights.length - 1];

	for (let i = 0; i < heights.length - 1; i++) {
		if (H_proem >= heights[i] && H_proem <= heights[i + 1]) {
			lowerHeight = heights[i];
			upperHeight = heights[i + 1];
			break;
		}
	}

	const heightRatio = (H_proem - lowerHeight) / (upperHeight - lowerHeight);

	// Интерполируем по ширине для обеих высот
	const lowerData = interpolateWidth(table[lowerHeight], W_proem);
	const upperData = interpolateWidth(table[upperHeight], W_proem);

	// Финальная интерполяция по высоте
	return {
		height: lerp(lowerData.height, upperData.height, heightRatio),
		topWidth: lerp(lowerData.topWidth, upperData.topWidth, heightRatio),
		bottomWidth: lerp(lowerData.bottomWidth, upperData.bottomWidth, heightRatio),
	};
}

/**
 * Основная функция расчета
 */
export function calcSlideGateFrame(H_proem, W_proem, isRectangular = false) {
	// Ограничения диапазона
	H_proem = Math.max(1500, Math.min(3000, H_proem));
	W_proem = Math.max(2000, Math.min(8000, W_proem));

	const result = interpolateFromTable(W_proem, H_proem, isRectangular);
	const catet = calcBeamCatet(H_proem, W_proem, isRectangular);
	const diagonal = calcDiagonalBeam(result.height, catet);
	const stiffener1 = result.height/100 * 54 ;
	const stiffener2 = calcDiagonalBeam(result.height/2, stiffener1,) 

	return {
		height: Math.round(result.height),
		topWidth: Math.round(result.topWidth),
		bottomWidth: Math.round(result.bottomWidth),
		catet, // горизонтальный катет наклонного ребра
		diagonal, // длина наклонного ребра (гипотенуза)
		stiffener1,
		stiffener2
	};
}
