/**
 * Интерполяция по ключевым точкам (универсальная)
 */
function interpolateByKeyPoints(points, value) {
	value = Math.max(points[0][0], Math.min(points[points.length - 1][0], value));
	let idx = 0;
	for (let i = 0; i < points.length - 1; i++) {
		if (value >= points[i][0] && value <= points[i + 1][0]) {
			idx = i;
			break;
		}
	}
	const [v0, r0] = points[idx];
	const [v1, r1] = points[idx + 1];
	return r0 + (r1 - r0) * ((value - v0) / (v1 - v0));
}
/**
 * Двумерная интерполяция по таблице разниц
 */
function interpolateDiffTable(table, H, W) {
	const heights = Object.keys(table)
		.map(Number)
		.sort((a, b) => a - b);
	let lowerH = heights[0];
	let upperH = heights[heights.length - 1];
	for (let i = 0; i < heights.length - 1; i++) {
		if (H >= heights[i] && H <= heights[i + 1]) {
			lowerH = heights[i];
			upperH = heights[i + 1];
			break;
		}
	}
	const diffLower = interpolateByKeyPoints(table[lowerH], W);
	const diffUpper = interpolateByKeyPoints(table[upperH], W);
	const ratio = (H - lowerH) / (upperH - lowerH);
	return diffLower + (diffUpper - diffLower) * ratio;
}

/**
 * Расчет горизонтального катета наклонного ребра
 * Для triangular: catet = bottomWidth - topWidth
 * Для rectangular: catet = catet_tri + diff / 2
 *   где diff = bottomWidth_rect - bottomWidth_tri
 */
export function calcBeamCatet(H_proem, W_proem, isRectangular) {
	H_proem = Math.max(1500, Math.min(3000, H_proem));
	W_proem = Math.max(2000, Math.min(8000, W_proem));

	// Получаем данные triangular (базовые)
	const triResult = interpolateFromTable(W_proem, H_proem, false);
	const catetTri = triResult.bottomWidth - triResult.topWidth;

	if (!isRectangular) {
		return Math.round(catetTri);
	}

	// Для rectangular: корректируем катет
	const diff = interpolateDiffTable(BOTTOM_WIDTH_DIFF_TABLE, H_proem, W_proem);
	const catetRect = catetTri + diff / 2;

	return Math.round(catetRect);
}

/**
 * Расчет длины наклонного ребра (гипотенузы)
 */
export function calcDiagonalBeam(H_gate, catet) {
	return Math.round(Math.sqrt(H_gate * H_gate + catet * catet));
}

